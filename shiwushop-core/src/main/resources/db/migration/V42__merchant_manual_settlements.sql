CREATE TABLE manual_settlements (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 shop_id BIGINT NOT NULL,
 payee_user_id BIGINT NOT NULL,
 created_by_user_id BIGINT NOT NULL,
 request_key VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 request_hash VARBINARY(32) NOT NULL,
 status VARCHAR(16) NOT NULL,
 amount DECIMAL(18,2) NOT NULL DEFAULT 0,
 approved_by_user_id BIGINT NULL,
 approved_at DATETIME(3) NULL,
 approval_key VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
 processing_by_user_id BIGINT NULL,
 processing_at DATETIME(3) NULL,
 processing_key VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
 paid_by_user_id BIGINT NULL,
 paid_at DATETIME(3) NULL,
 paid_amount DECIMAL(18,2) NULL,
 payment_method VARCHAR(32) NULL,
 external_reference VARCHAR(128) NULL,
 proof_reference VARCHAR(255) NULL,
 payment_key VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
 payment_hash VARBINARY(32) NULL,
 voided_by_user_id BIGINT NULL,
 voided_at DATETIME(3) NULL,
 void_key VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
 void_reason VARCHAR(500) NULL,
 no_payment_evidence VARCHAR(255) NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
 UNIQUE KEY uk_manual_settlement_request(created_by_user_id,request_key),
 KEY ix_manual_settlement_payee(payee_user_id,id),
 KEY ix_manual_settlement_shop(shop_id,id),
 CONSTRAINT fk_manual_settlement_shop FOREIGN KEY(shop_id) REFERENCES shops(id) ON DELETE RESTRICT,
 CONSTRAINT fk_manual_settlement_payee FOREIGN KEY(payee_user_id) REFERENCES users(id) ON DELETE RESTRICT,
 CONSTRAINT fk_manual_settlement_creator FOREIGN KEY(created_by_user_id) REFERENCES users(id) ON DELETE RESTRICT,
 CONSTRAINT fk_manual_settlement_approver FOREIGN KEY(approved_by_user_id) REFERENCES users(id) ON DELETE RESTRICT,
 CONSTRAINT fk_manual_settlement_processor FOREIGN KEY(processing_by_user_id) REFERENCES users(id) ON DELETE RESTRICT,
 CONSTRAINT fk_manual_settlement_payer FOREIGN KEY(paid_by_user_id) REFERENCES users(id) ON DELETE RESTRICT,
 CONSTRAINT fk_manual_settlement_voider FOREIGN KEY(voided_by_user_id) REFERENCES users(id) ON DELETE RESTRICT,
 CONSTRAINT ck_manual_settlement_status CHECK(status IN ('DRAFT','APPROVED','PROCESSING','PAID','VOID')),
 CONSTRAINT ck_manual_settlement_amount CHECK(amount>=0 AND (paid_amount IS NULL OR paid_amount>0)),
 CONSTRAINT ck_manual_settlement_payment CHECK((status='PAID')=(paid_at IS NOT NULL AND paid_amount IS NOT NULL
   AND paid_by_user_id IS NOT NULL AND payment_method IS NOT NULL AND payment_key IS NOT NULL
   AND (external_reference IS NOT NULL OR proof_reference IS NOT NULL))),
 CONSTRAINT ck_manual_settlement_void CHECK((status='VOID')=(voided_at IS NOT NULL AND voided_by_user_id IS NOT NULL
   AND void_reason IS NOT NULL AND no_payment_evidence IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='管理员人工付款结算单；登记不代表渠道到账';

CREATE TABLE manual_settlement_lines (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 settlement_id BIGINT NOT NULL,
 order_id BIGINT NOT NULL,
 owner_user_id_at_order BIGINT NULL,
 ownership_evidence VARCHAR(255) NOT NULL,
 cash_paid DECIMAL(18,2) NOT NULL,
 cash_refunded DECIMAL(18,2) NOT NULL,
 platform_subsidy DECIMAL(18,2) NOT NULL,
 platform_reversal DECIMAL(18,2) NOT NULL,
 cost_platform DECIMAL(18,2) NOT NULL,
 cost_reversal DECIMAL(18,2) NOT NULL,
 payable_amount DECIMAL(18,2) NOT NULL,
 source_hash VARBINARY(32) NOT NULL,
 included_refund_case_ids JSON NOT NULL,
 active TINYINT NOT NULL DEFAULT 1,
 active_order_id BIGINT GENERATED ALWAYS AS (CASE WHEN active=1 THEN order_id ELSE NULL END) STORED,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 UNIQUE KEY uk_manual_settlement_line(settlement_id,order_id),
 UNIQUE KEY uk_manual_settlement_active_order(active_order_id),
 KEY ix_manual_settlement_line_order(order_id,id),
 CONSTRAINT fk_manual_settlement_line_head FOREIGN KEY(settlement_id) REFERENCES manual_settlements(id) ON DELETE RESTRICT,
 CONSTRAINT fk_manual_settlement_line_order FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE RESTRICT,
 CONSTRAINT fk_manual_settlement_line_owner FOREIGN KEY(owner_user_id_at_order) REFERENCES users(id) ON DELETE RESTRICT,
 CONSTRAINT ck_manual_settlement_line_active CHECK(active IN (0,1)),
 CONSTRAINT ck_manual_settlement_line_amount CHECK(cash_paid>=0 AND cash_refunded>=0
   AND platform_subsidy>=0 AND platform_reversal>=0 AND cost_platform>=0 AND cost_reversal>=0
   AND payable_amount>0 AND payable_amount=cash_paid-cash_refunded+platform_subsidy-platform_reversal
     +cost_platform-cost_reversal)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='逐订单冻结原事实；作废只释放有效占用';

CREATE TABLE manual_settlement_adjustments (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 settlement_id BIGINT NOT NULL,
 line_id BIGINT NULL,
 source_case_id BIGINT NULL,
 request_key VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 request_hash VARBINARY(32) NOT NULL,
 kind VARCHAR(24) NOT NULL,
 amount_delta DECIMAL(18,2) NOT NULL DEFAULT 0,
 proposed_payee_user_id BIGINT NULL,
 replacement_method VARCHAR(32) NULL,
 replacement_external_reference VARCHAR(128) NULL,
 replacement_proof_reference VARCHAR(255) NULL,
 reason VARCHAR(500) NOT NULL,
 evidence_reference VARCHAR(255) NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'OPEN',
 created_by_user_id BIGINT NOT NULL,
 reviewed_by_user_id BIGINT NULL,
 reviewed_at DATETIME(3) NULL,
 review_key VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
 review_evidence_reference VARCHAR(255) NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 UNIQUE KEY uk_manual_adjustment_request(settlement_id,request_key),
 UNIQUE KEY uk_manual_adjustment_refund(line_id,source_case_id),
 KEY ix_manual_adjustment_open(status,id),
 CONSTRAINT fk_manual_adjustment_head FOREIGN KEY(settlement_id) REFERENCES manual_settlements(id) ON DELETE RESTRICT,
 CONSTRAINT fk_manual_adjustment_line FOREIGN KEY(line_id) REFERENCES manual_settlement_lines(id) ON DELETE RESTRICT,
 CONSTRAINT fk_manual_adjustment_case FOREIGN KEY(source_case_id) REFERENCES after_sale_cases(id) ON DELETE RESTRICT,
 CONSTRAINT fk_manual_adjustment_payee FOREIGN KEY(proposed_payee_user_id) REFERENCES users(id) ON DELETE RESTRICT,
 CONSTRAINT fk_manual_adjustment_creator FOREIGN KEY(created_by_user_id) REFERENCES users(id) ON DELETE RESTRICT,
 CONSTRAINT fk_manual_adjustment_reviewer FOREIGN KEY(reviewed_by_user_id) REFERENCES users(id) ON DELETE RESTRICT,
 CONSTRAINT ck_manual_adjustment_kind CHECK(kind IN ('REFUND','AMOUNT','PAYEE','EVIDENCE')),
 CONSTRAINT ck_manual_adjustment_status CHECK(status IN ('OPEN','REVIEWED')),
 CONSTRAINT ck_manual_adjustment_review CHECK((status='REVIEWED')=(reviewed_at IS NOT NULL
   AND reviewed_by_user_id IS NOT NULL AND review_key IS NOT NULL AND review_evidence_reference IS NOT NULL)),
 CONSTRAINT ck_manual_adjustment_refund CHECK((kind='REFUND')=(source_case_id IS NOT NULL AND line_id IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='已付款后来源退款及人工错误更正待核对记录';
